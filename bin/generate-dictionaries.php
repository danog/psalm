#!/usr/bin/env php
<?php
/**
 * Regenerates src/Psalm/Internal/Dictionaries/*.php from the dictionaries/ directory.
 *
 * Psalm loads its dictionaries through these generated classes instead of
 * `require`-ing the dictionary files at runtime, so that a closed-world (ahead of
 * time compiled) build of Psalm contains no runtime code loading.
 *
 * Usage: bin/generate-dictionaries.php [--check]
 */

declare(strict_types=1);

require __DIR__ . '/../vendor/autoload.php';

$check = in_array('--check', $argv, true);
$root = dirname(__DIR__);
$target_dir = $root . '/src/Psalm/Internal/Dictionaries';

$dictionaries = [
    'PropertyMap' => 'PropertyMap.php',
    'ImpureFunctionsList' => 'ImpureFunctionsList.php',
    'InternalTaintSinkMap' => 'InternalTaintSinkMap.php',
];
foreach (glob($root . '/dictionaries/CallMap_[0-9]*.php') as $file) {
    $dictionaries['CallMap' . substr(basename($file, '.php'), 8)] = basename($file);
}

$stale = [];
foreach ($dictionaries as $class => $file) {
    /** @var array $data */
    $data = require $root . '/dictionaries/' . $file;
    $blob = base64_encode(gzencode(json_encode($data, JSON_THROW_ON_ERROR), 9));
    $content = "<?php // phpcs:ignoreFile\n\n"
        . "/**\n * Generated by bin/generate-dictionaries.php from dictionaries/$file - do not edit.\n */\n\n"
        . "declare(strict_types=1);\n\nnamespace Psalm\\Internal\\Dictionaries;\n\n"
        . "/**\n * @internal\n */\nfinal class $class\n{\n"
        . "    /** base64 encoded, gzip compressed JSON */\n"
        . "    public const DATA = <<<'DATA'\n" . chunk_split($blob, 120, "\n") . "DATA;\n}\n";
    $target = $target_dir . '/' . $class . '.php';
    if ($check) {
        if (!file_exists($target) || file_get_contents($target) !== $content) {
            $stale[] = $target;
        }
        continue;
    }
    file_put_contents($target, $content);
    echo "wrote $target\n";
}

if ($stale) {
    fwrite(STDERR, "Out of date, run bin/generate-dictionaries.php:\n  " . implode("\n  ", $stale) . "\n");
    exit(1);
}

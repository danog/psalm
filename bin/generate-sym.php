    'ITERATOR_AGGREGATE' => 'IteratorAggregate',
    'THROWABLE' => 'Throwable',
    'EXCEPTION' => 'Exception',
    'ERROR' => 'Error',
    'STD_CLASS' => 'stdClass',
    'GENERATOR' => 'Generator',
    'COUNTABLE' => 'Countable',
    'STRINGABLE' => 'Stringable',
    'SELF' => 'self',
    'STATIC' => 'static',
    'PARENT' => 'parent',
    'THIS_VAR' => '$this',
    'DOM_DOCUMENT' => 'DOMDocument',
    'DATE_TIME' => 'DateTime',
    'DATE_TIME_IMMUTABLE' => 'DateTimeImmutable',
    'DATE_TIME_INTERFACE' => 'DateTimeInterface',
    'MESSAGE_FORMATTER' => 'MessageFormatter',
    'NUMBER_FORMATTER' => 'NumberFormatter',
    'REFLECTION_CLASS' => 'ReflectionClass',
    'REFLECTION_FUNCTION' => 'ReflectionFunction',
    'SIMPLE_XML_ELEMENT' => 'SimpleXMLElement',
    'SIMPLE_XML_ITERATOR' => 'SimpleXMLIterator',
    'PHP_INCOMPLETE_CLASS' => '__PHP_Incomplete_Class',
    // more of the names Psalm's analyzers compare against
    'ARRAY_ACCESS' => 'ArrayAccess',
    'ARRAY_OBJECT' => 'ArrayObject',
    'ARRAY_ITERATOR' => 'ArrayIterator',
    'UNIT_ENUM' => 'UnitEnum',
    'BACKED_ENUM' => 'BackedEnum',
    'SPL_OBJECT_STORAGE' => 'SplObjectStorage',

// Member (method, property, constant) names: the storages key their member maps by the id of the canonical
// lowercase spelling (Psalm resolves members case-insensitively for PHP semantics and keeps the declared casing
// on the storage), so these are interned lowercase.
$member_names = [
    'CONSTRUCT' => '__construct',
    'DESTRUCT' => '__destruct',
    'CALL' => '__call',
    'CALL_STATIC' => '__callStatic',
    'GET' => '__get',
    'SET' => '__set',
    'ISSET' => '__isset',
    'UNSET' => '__unset',
    'SLEEP' => '__sleep',
    'WAKEUP' => '__wakeup',
    'SERIALIZE' => '__serialize',
    'UNSERIALIZE' => '__unserialize',
    'TO_STRING' => '__toString',
    'INVOKE' => '__invoke',
    'SET_STATE' => '__set_state',
    'CLONE' => '__clone',
    'DEBUG_INFO' => '__debugInfo',
    'OFFSET_GET' => 'offsetGet',
    'OFFSET_SET' => 'offsetSet',
    'OFFSET_EXISTS' => 'offsetExists',
    'OFFSET_UNSET' => 'offsetUnset',
    'GET_ITERATOR' => 'getIterator',
    'COUNT' => 'count',
    'CURRENT' => 'current',
    'KEY' => 'key',
    'NEXT' => 'next',
    'REWIND' => 'rewind',
    'VALID' => 'valid',
    'CASES' => 'cases',
    'FROM' => 'from',
    'TRY_FROM' => 'tryFrom',
    'NAME' => 'name',
    'VALUE' => 'value',
    'JSON_SERIALIZE' => 'jsonSerialize',
    'CLASS_CONST' => 'class',
];
foreach ($member_names as $const => $name) {
    $names[$const] = strtolower($name);
}

$seen = [];
foreach ($names as $const => $name) {
    if (isset($seen[$name])) {
        fwrite(STDERR, "duplicate preloaded name: $name\n");
        exit(1);
    }
    $seen[$name] = true;
}

$out = "<?php\n\ndeclare(strict_types=1);\n\nnamespace Psalm\\Internal;\n\n/**\n * The interned ids (Interner::hash) of the names Psalm's own code refers to: pzoom's generated `StrId`\n * constants. Generated by bin/generate-sym.php; do not edit.\n *\n * @internal\n * @psalm-immutable\n */\nfinal class Sym\n{\n";
foreach ($names as $const => $name) {
    $out .= sprintf("    /** `%s` */\n    public const %s = %d;\n", $name === '' ? '' : $name, $const, Interner::hash($name));
}
$out .= "\n    /**\n     * The preloaded names, interned at startup so their ids resolve in every process.\n     *\n     * @var list<string>\n     */\n    public const PRELOADED = [\n";
foreach ($names as $name) {
    $out .= "        " . var_export($name, true) . ",\n";
}
$out .= "    ];\n}\n";

file_put_contents(__DIR__ . '/../src/Psalm/Internal/Sym.php', $out);
echo "wrote " . count($names) . " constants\n";

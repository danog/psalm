    'MIXED' => 'mixed',
    'ITERABLE' => 'iterable',
    'CALLABLE' => 'callable',
    'OBJECT' => 'object',
    // added by tools/id-refactor
    'C_NON_EMPTY_ARRAY' => 'non-empty-array',
    'C_ARRAY' => 'array',

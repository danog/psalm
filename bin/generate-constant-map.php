<?php
/**
 * Generates dictionaries/ConstantMap.php: the internal (non-user) constants of the PHP that runs this script, as
 * the analyzer's model of PHP's constants. Psalm read get_defined_constants() of its own runtime at every use;
 * the fork and the compiled program read this table instead.
 */

declare(strict_types=1);

$all = get_defined_constants(true);
unset($all['user']);
$map = [];
foreach ($all as $constants) {
    foreach ($constants as $name => $value) {
        if (is_resource($value)) {
            continue; // STDIN, STDOUT, STDERR
        }
        $map[$name] = $value;
    }
}
ksort($map, SORT_STRING);

$export = static function (mixed $value): string {
    if (is_float($value) && !is_finite($value)) {
        return is_nan($value) ? 'NAN' : ($value > 0 ? 'INF' : '-INF');
    }
    return var_export($value, true);
};

$out = "<?php\n\n// Generated by bin/generate-constant-map.php from PHP " . PHP_VERSION . " (" . PHP_OS . ");"
    . " do not edit.\n"
    . "// The internal constants the analyzer models: name => value.\n\n"
    . "return [\n";
foreach ($map as $name => $value) {
    $out .= '    ' . var_export($name, true) . ' => ' . $export($value) . ",\n";
}
$out .= "];\n";

file_put_contents(__DIR__ . '/../dictionaries/ConstantMap.php', $out);
echo 'wrote ' . count($map) . " constants\n";

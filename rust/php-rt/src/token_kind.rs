//! `TokenKind` — a semantic PHP token enum (mago-style), decoupled from PHP's numeric `T_*`
//! constant values. The tokenizer emits these; the parser bridge maps each to its grammar symbol.
//!
//! Adopting an enum (instead of the numeric `T_*` ids) removes a whole class of bugs: the
//! transpiler used to inline the *host* PHP token-constant values for `\T_*` references while
//! php-rt's tokenizer + the parser tables used a *different* numeric scheme, so e.g. a by-reference
//! `&` (php-rt `T_AMPERSAND_FOLLOWED` = 409) collided with host `T_BAD_CHARACTER` = 409 and every
//! `&$var` was rejected as "Unexpected character &". With a by-name enum there are no numbers to
//! disagree on. Variant set mirrors carthage-software/mago's `TokenKind`.

/// A PHP lexical token kind. `&` disambiguation (by-ref vs bitwise vs intersection) is the parser's
/// job via lookahead, so there is a single `Ampersand` here (unlike PHP's `T_AMPERSAND_*` split).
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, PartialOrd, Ord)]
